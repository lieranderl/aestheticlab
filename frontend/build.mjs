// Builds the Go site's static files into static/dist/ (embedded by
// static/static.go, served under /static/dist/) and writes
// internal/assets/manifest_gen.go, which maps each source name to its
// content-hashed URL.
//
// Hashes come from source bytes and encoder settings, never from encoder
// output, so the manifest is the same on every machine and in CI; built
// files are not committed, the manifest is (make assets-check).
//
// Usage: bun run assets (after bun run icons, which writes the icon code the
// CSS scan reads).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { basename, dirname, extname, join, relative } from "node:path";
import { brotliCompressSync, constants, gzipSync } from "node:zlib";

const distDir = "static/dist";
const mediaDir = "src/media";
const manifestFile = "internal/assets/manifest_gen.go";

// What Qwik City asks vite-imagetools for today (format webp, quality 75,
// w 200;400;600;800;1200, withoutEnlargement): each width below the source
// width, then the source width itself capped at 1200.
export const imageWidths = [200, 400, 600, 800];
export const maxImageWidth = 1200;
export const webpQuality = 75;

// Text files get .br and .gz siblings, which internal/server serves to
// browsers that accept them.
const compressible = new Set([".css", ".js", ".svg"]);

/** The variant widths for a source this wide, smallest first. */
export function variantWidths(sourceWidth) {
	const top = Math.min(sourceWidth, maxImageWidth);
	return [...imageWidths.filter((w) => w < top), top];
}

/** The first 10 hex digits of the SHA-256 of the given parts. */
export function contentHash(...parts) {
	const h = createHash("sha256");
	for (const part of parts) h.update(part);
	return h.digest("hex").slice(0, 10);
}

/** stem.hash.ext: internal/server caches such names for a year. */
export function hashedName(stem, hash, ext) {
	return `${stem}.${hash}${ext}`;
}

/** Rewrites url(/static/fonts/x) and url(./files/x) to hashed URLs. */
export function rewriteFontURLs(css, fontURLs) {
	return css.replace(
		/url\((["']?)(?:\/static\/fonts\/|\.\/files\/)([^"')]+)\1\)/g,
		(match, _quote, file) => {
			const url = fontURLs.get(file);
			if (!url) throw new Error(`no built font for ${match}`);
			return `url("${url}")`;
		},
	);
}

// byName sorts entries by code point, the same on every machine (unlike
// localeCompare).
const byName = ([a], [b]) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * The Go source of internal/assets/manifest_gen.go: switch statements and
 * name lists, which gofmt leaves as they are (map literals it would align).
 */
export function renderManifest(files, images) {
	const q = JSON.stringify;
	const sortedFiles = [...files].sort(byName);
	const sortedImages = [...images].sort(byName);
	const fileCases = sortedFiles.map(
		([name, url]) => `\tcase ${q(name)}:\n\t\treturn ${q(url)}`,
	);
	const imageCases = sortedImages.map(
		([name, img]) =>
			`\tcase ${q(name)}:\n\t\treturn Image{Src: ${q(img.src)}, SrcSet: ${q(img.srcset)}, Width: ${img.width}, Height: ${img.height}}, true`,
	);
	const list = (entries) => entries.map(([name]) => `\t${q(name)},`).join("\n");
	return `// Code generated by frontend/build.mjs; DO NOT EDIT.

package assets

// fileURL is the content-hashed URL of a built file, or "".
func fileURL(name string) string {
	switch name {
${fileCases.join("\n")}
	}
	return ""
}

// image is a source image's WebP variants.
func image(name string) (Image, bool) {
	switch name {
${imageCases.join("\n")}
	}
	return Image{}, false
}

var fileNames = []string{
${list(sortedFiles)}
}

var imageNames = []string{
${list(sortedImages)}
}
`;
}

/** Writes path only when its bytes change, so watchers (Air) do not loop. */
function writeIfChanged(path, data) {
	const next = typeof data === "string" ? Buffer.from(data) : data;
	if (existsSync(path) && readFileSync(path).equals(next)) return false;
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, next);
	return true;
}

// walk lists dir's files in sorted order, skipping hidden ones (.DS_Store).
function walk(dir) {
	return readdirSync(dir)
		.filter((f) => !f.startsWith("."))
		.sort()
		.flatMap((f) => {
			const p = join(dir, f);
			return statSync(p).isDirectory() ? walk(p) : [p];
		});
}

async function build() {
	const { default: sharp } = await import("sharp");
	const sharpVersion = JSON.parse(
		readFileSync("node_modules/sharp/package.json", "utf8"),
	).version;
	const written = new Set();
	const files = new Map();
	const images = new Map();

	// emit writes dist/<rel> (unless it exists: names are content-hashed) and
	// returns its URL.
	const emit = async (rel, produce) => {
		const path = join(distDir, rel);
		if (!existsSync(path)) {
			mkdirSync(dirname(path), { recursive: true });
			writeFileSync(path, await produce());
		}
		written.add(rel);
		if (compressible.has(extname(rel))) {
			const bytes = readFileSync(path);
			for (const [suffix, pack] of [
				[
					".br",
					(b) =>
						brotliCompressSync(b, {
							params: { [constants.BROTLI_PARAM_QUALITY]: 11 },
						}),
				],
				[".gz", (b) => gzipSync(b, { level: 9 })],
			]) {
				if (!existsSync(path + suffix))
					writeFileSync(path + suffix, pack(bytes));
				written.add(rel + suffix);
			}
		}
		return `/static/dist/${rel}`;
	};
	// Byte-identical sources share one set of built files, named after the
	// first source (in sorted order) with those bytes.
	const relByHash = new Map();
	const canonical = (hash, rel) => {
		if (!relByHash.has(hash)) relByHash.set(hash, rel);
		return relByHash.get(hash);
	};
	const copy = (src, rel) => {
		const bytes = readFileSync(src);
		const hash = contentHash(bytes);
		const first = canonical(hash, rel);
		const ext = extname(first);
		return emit(
			join(dirname(first), hashedName(basename(first, ext), hash, ext)),
			() => bytes,
		);
	};

	// Fonts: Onest from @fontsource-variable/onest, the rest from public/fonts.
	const fontURLs = new Map();
	const onestDir = "node_modules/@fontsource-variable/onest";
	const fontSources = [
		...walk(join(onestDir, "files")).filter((f) => f.endsWith(".woff2")),
		...walk("public/fonts"),
	];
	for (const src of fontSources) {
		const url = await copy(src, `fonts/${basename(src)}`);
		fontURLs.set(basename(src), url);
		files.set(`fonts/${basename(src)}`, url);
	}
	writeIfChanged(
		"frontend/generated/fonts.css",
		rewriteFontURLs(
			readFileSync(join(onestDir, "index.css"), "utf8"),
			fontURLs,
		),
	);

	// CSS: Tailwind 4 + DaisyUI 5, then hashed font URLs.
	const rawCSS = "frontend/generated/app.css";
	execFileSync(
		"node_modules/.bin/tailwindcss",
		["-i", "frontend/app.css", "-o", rawCSS, "--minify"],
		{ stdio: ["ignore", "ignore", "inherit"] },
	);
	const css = rewriteFontURLs(readFileSync(rawCSS, "utf8"), fontURLs);
	files.set(
		"app.css",
		await emit(hashedName("app", contentHash(css), ".css"), () => css),
	);

	// Datastar, vendored at a pinned version.
	files.set(
		"datastar.js",
		await copy("frontend/vendor/datastar.js", "datastar.js"),
	);

	// Media: raster images become WebP variants; videos, their posters and
	// SVGs are copied.
	for (const src of walk(mediaDir)) {
		const name = relative(mediaDir, src);
		const ext = extname(src).toLowerCase();
		const raster = [".jpg", ".jpeg", ".png", ".webp"].includes(ext);
		if (!raster || name.startsWith("video/")) {
			files.set(name, await copy(src, `media/${name}`));
			continue;
		}
		const bytes = readFileSync(src);
		const first = canonical(contentHash(bytes), name);
		const stem = join(dirname(first), basename(first, extname(first)));
		// Rotated per EXIF orientation, as the Qwik site renders them.
		const { width, height } = (await sharp(bytes).metadata()).autoOrient;
		const variants = [];
		for (const w of variantWidths(width)) {
			const hash = contentHash(
				bytes,
				`webp|q${webpQuality}|w${w}|sharp${sharpVersion}`,
			);
			const url = await emit(
				`media/${hashedName(`${stem}-${w}`, hash, ".webp")}`,
				() =>
					sharp(bytes)
						.rotate()
						.resize({ width: w })
						.webp({ quality: webpQuality })
						.toBuffer(),
			);
			variants.push({ url, w });
		}
		const largest = variants.at(-1);
		images.set(name, {
			src: largest.url,
			srcset: variants.map((v) => `${v.url} ${v.w}w`).join(", "),
			width: largest.w,
			height: Math.round((height * largest.w) / width),
		});
	}

	// Drop files from earlier builds that this one did not produce.
	let pruned = 0;
	for (const path of walk(distDir)) {
		const rel = relative(distDir, path);
		if (rel === ".gitkeep" || written.has(rel)) continue;
		rmSync(path);
		pruned++;
	}

	const changed = writeIfChanged(manifestFile, renderManifest(files, images));
	console.log(
		`assets: ${files.size} files, ${images.size} images, ${written.size} built files (${pruned} pruned)${changed ? `; wrote ${manifestFile}` : ""}`,
	);
}

if (import.meta.main) await build();
