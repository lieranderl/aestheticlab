// Generates internal/views/icons_gen.go: the inner SVG markup of every icon
// the templates use, so the binary embeds only those and pages render icons
// on the server.
//
// Names are "outline/<heroicon>" (24px outline), "mini/<heroicon>" (20px
// solid) and "brand/<simple-icons slug>", the sets the Qwik site renders
// through @qwikest/icons, and "logo/bird", the studio's mark (src/media/Bird.svg). Templates are scanned for those string literals;
// the icons the Qwik site uses today are always included.
//
// Usage: bun run icons
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as simpleIcons from "simple-icons";

const viewsDir = "internal/views";
const outFile = join(viewsDir, "icons_gen.go");

// The Qwik site's icons (HiArrowLongRightOutline, HiPauseMini, SiInstagram, …).
export const qwikIcons = [
	"outline/arrow-long-right",
	"outline/arrow-up",
	"outline/map-pin",
	"mini/arrow-path",
	"mini/pause",
	"mini/play",
	"brand/instagram",
	"logo/bird",
];

// The studio's marks, by slug: drawn in currentColor like the icons.
const logos = { bird: "src/media/Bird.svg" };

const heroiconsDir = { outline: "24/outline", mini: "20/solid" };

/** The icon names a template mentions. */
export function iconNames(templ) {
	return [
		...templ.matchAll(
			/"((?:outline|mini|brand|logo)\/[a-z0-9]+(?:-[a-z0-9]+)*)"/g,
		),
	].map((m) => m[1]);
}

/** The inner markup of a Heroicons SVG file, or "" when it has none. */
export function svgInner(svg) {
	const m = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg);
	return m ? m[1].replace(/>\s+</g, "><").trim() : "";
}

const toPascal = (slug) =>
	slug.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

/** The inner SVG markup for name, or "" when no set has it. */
export function iconMarkup(name, readFile = readFileSync) {
	const [set, slug] = name.split("/");
	if (set === "logo") {
		const file = logos[slug];
		return file
			? svgInner(readFile(file, "utf8"))
					.replace(/<title>[^<]*<\/title>/, "")
					.replace(/ fill="[^"]*"/g, "")
			: "";
	}
	if (set === "brand") {
		const icon = simpleIcons[`si${toPascal(slug)}`];
		return icon ? `<path d="${icon.path}"/>` : "";
	}
	const path = join("node_modules/heroicons", heroiconsDir[set], `${slug}.svg`);
	return existsSync(path) ? svgInner(readFile(path, "utf8")) : "";
}

/** The Go source of icons_gen.go for these names. */
export function renderIcons(names) {
	const cases = [...new Set(names)].sort().map((name) => {
		const markup = iconMarkup(name);
		if (!markup) throw new Error(`unknown icon ${name}`);
		return `\tcase ${JSON.stringify(name)}:\n\t\treturn ${JSON.stringify(markup)}`;
	});
	return `// Code generated by frontend/icons.mjs; DO NOT EDIT.

package views

// iconPath returns the inner SVG markup of an icon, or "" if unknown.
func iconPath(name string) string {
	switch name {
${cases.join("\n")}
	default:
		return ""
	}
}
`;
}

function generate() {
	const names = [...qwikIcons];
	for (const file of readdirSync(viewsDir)) {
		if (file.endsWith(".templ"))
			names.push(...iconNames(readFileSync(join(viewsDir, file), "utf8")));
	}
	const out = renderIcons(names);
	// Write only on change so watchers (Air) do not loop on regeneration.
	const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : null;
	if (current !== out) {
		writeFileSync(outFile, out);
		console.log(`icons: wrote ${new Set(names).size} icons to ${outFile}`);
	}
}

if (import.meta.main) generate();
