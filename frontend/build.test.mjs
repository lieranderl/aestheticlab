import { describe, expect, test } from "bun:test";
import {
	contentHash,
	hashedName,
	renderManifest,
	rewriteFontURLs,
	variantWidths,
} from "./build.mjs";

describe("variant widths", () => {
	test("match the Qwik site's: each step below the source, then the source", () => {
		expect(variantWidths(941)).toEqual([200, 400, 600, 800, 941]);
		expect(variantWidths(1120)).toEqual([200, 400, 600, 800, 1120]);
	});

	test("stop at 1200 for wider sources", () => {
		expect(variantWidths(1687)).toEqual([200, 400, 600, 800, 1200]);
		expect(variantWidths(1200)).toEqual([200, 400, 600, 800, 1200]);
	});

	test("never upscale a small source", () => {
		expect(variantWidths(150)).toEqual([150]);
		expect(variantWidths(400)).toEqual([200, 400]);
	});
});

describe("hashed names", () => {
	test("depend only on content, so every machine builds the same manifest", () => {
		expect(contentHash("abc")).toBe(contentHash("abc"));
		expect(contentHash("abc")).toHaveLength(10);
		expect(contentHash("abc")).not.toBe(contentHash("abd"));
		expect(contentHash("a", "bc")).toBe(contentHash("abc"));
	});

	test("are stem.hash.ext, which internal/server caches for a year", () => {
		expect(hashedName("app", "0123456789", ".css")).toBe("app.0123456789.css");
	});
});

describe("font URLs", () => {
	const urls = new Map([
		[
			"onest-latin-wght-normal.woff2",
			"/static/dist/fonts/onest-latin.aaa.woff2",
		],
		["QESTERO-Regular.ttf", "/static/dist/fonts/QESTERO-Regular.bbb.ttf"],
	]);

	test("point at the hashed copies, in fontsource's and our own form", () => {
		const css =
			"src: url(./files/onest-latin-wght-normal.woff2) format('woff2'); " +
			"src: url('/static/fonts/QESTERO-Regular.ttf'); " +
			'src: url("/static/fonts/QESTERO-Regular.ttf");';
		expect(rewriteFontURLs(css, urls)).toBe(
			"src: url(\"/static/dist/fonts/onest-latin.aaa.woff2\") format('woff2'); " +
				'src: url("/static/dist/fonts/QESTERO-Regular.bbb.ttf"); ' +
				'src: url("/static/dist/fonts/QESTERO-Regular.bbb.ttf");',
		);
	});

	test("fail the build when a stylesheet names a font that was not built", () => {
		expect(() =>
			rewriteFontURLs("src: url(/static/fonts/missing.woff2)", urls),
		).toThrow("no built font");
	});

	test("leave other URLs alone", () => {
		const css = "background: url(data:image/svg+xml,abc)";
		expect(rewriteFontURLs(css, urls)).toBe(css);
	});
});

describe("manifest", () => {
	test("is Go source sorted by name, so rebuilding writes the same bytes", () => {
		const files = new Map([
			["video/nude.mp4", "/static/dist/media/video/nude.1.mp4"],
			["app.css", "/static/dist/app.2.css"],
		]);
		const images = new Map([
			[
				"julia.jpg",
				{
					src: "/j-400.webp",
					srcset: "/j-200.webp 200w, /j-400.webp 400w",
					width: 400,
					height: 600,
				},
			],
		]);
		const go = renderManifest(files, images);
		expect(go).toStartWith(
			"// Code generated by frontend/build.mjs; DO NOT EDIT.",
		);
		expect(go).toContain("package assets");
		expect(go).toContain(
			'\tcase "app.css":\n\t\treturn "/static/dist/app.2.css"',
		);
		expect(go).toContain(
			'\tcase "julia.jpg":\n\t\treturn Image{Src: "/j-400.webp", SrcSet: "/j-200.webp 200w, /j-400.webp 400w", Width: 400, Height: 600}, true',
		);
		expect(go).toContain(
			'var fileNames = []string{\n\t"app.css",\n\t"video/nude.mp4",\n}',
		);
		expect(renderManifest(new Map([...files].reverse()), images)).toBe(go);
	});

	test("sorts by code point, not locale, so CI and laptops agree", () => {
		const files = new Map([
			["app.css", "/a"],
			["Bird.svg", "/b"],
		]);
		const go = renderManifest(files, new Map());
		expect(go.indexOf('"Bird.svg"')).toBeLessThan(go.indexOf('"app.css"'));
	});
});
