import { describe, expect, test } from "bun:test";
import {
	iconMarkup,
	iconNames,
	qwikIcons,
	renderIcons,
	svgInner,
} from "./icons.mjs";

describe("icon names", () => {
	test("are found in templates as set/slug string literals", () => {
		const templ = `@Icon("outline/map-pin", "size-4") @Icon("mini/play", "") "not/an-icon" "brand/instagram"`;
		expect(iconNames(templ)).toEqual([
			"outline/map-pin",
			"mini/play",
			"brand/instagram",
		]);
	});
});

describe("icon markup", () => {
	test("is the inner SVG of a Heroicons file", () => {
		expect(
			svgInner(
				'<svg xmlns="x" viewBox="0 0 24 24">\n  <path d="M1 2"/>\n</svg>',
			),
		).toBe('<path d="M1 2"/>');
	});

	test("exists for every icon the Qwik site renders today", () => {
		for (const name of qwikIcons) expect(iconMarkup(name)).toContain("<path");
	});

	test("is empty for an icon no set has", () => {
		expect(iconMarkup("outline/no-such-icon")).toBe("");
		expect(iconMarkup("brand/no-such-brand")).toBe("");
	});
});

describe("generated Go", () => {
	test("lists each icon once, sorted, and fails on unknown names", () => {
		const go = renderIcons(["mini/play", "outline/map-pin", "mini/play"]);
		expect(go).toStartWith(
			"// Code generated by frontend/icons.mjs; DO NOT EDIT.",
		);
		expect(go.match(/case "mini\/play":/g)).toHaveLength(1);
		expect(go.indexOf('"mini/play"')).toBeLessThan(
			go.indexOf('"outline/map-pin"'),
		);
		expect(() => renderIcons(["outline/no-such-icon"])).toThrow("unknown icon");
	});
});
